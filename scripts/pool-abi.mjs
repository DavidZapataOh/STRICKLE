import { readFileSync, writeFileSync } from "node:fs";

const artifact = new URL("../contracts/out/PolicyPool.sol/PolicyPool.json", import.meta.url);
const target = new URL("../packages/pool/src/abi.ts", import.meta.url);

export function renderAbi(abi) {
  return `// GENERATED by \`npm run pool:abi\` from the PolicyPool build output. Do not edit.\nexport const poolAbi = ${JSON.stringify(abi, null, 2)} as const;\n`;
}

if (import.meta.main) {
  writeFileSync(target, renderAbi(JSON.parse(readFileSync(artifact, "utf8")).abi));
}
