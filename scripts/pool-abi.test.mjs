import assert from "node:assert/strict";
import { test } from "node:test";
import { renderAbi } from "./pool-abi.mjs";

test("renders the ABI as a typed constant with a generated-file header", () => {
  const abi = [{ type: "function", name: "paused", inputs: [], outputs: [{ type: "bool" }], stateMutability: "view" }];
  const source = renderAbi(abi);
  assert.match(source, /^\/\/ GENERATED by `npm run pool:abi`/);
  assert.match(source, /export const poolAbi = \[/);
  assert.match(source, /\] as const;\n$/);
  assert.match(source, /"name": "paused"/);
});

test("is deterministic so a stale committed file shows up as a diff", () => {
  const abi = [{ type: "event", name: "Paused", inputs: [], anonymous: false }];
  assert.equal(renderAbi(abi), renderAbi(abi));
});
